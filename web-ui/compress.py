#!/usr/bin/env python3
"""
Compress and embed web-ui/index.html into shore-station/src/web_ui.h
Supports raw PROGMEM string literal generation with whitespace trimming.
"""

import os
import sys

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(script_dir)
    html_path = os.path.join(script_dir, "index.html")
    output_header = os.path.join(project_root, "boat-controller", "src", "web_ui.h")

    if not os.path.exists(html_path):
        print(f"Error: {html_path} not found!")
        sys.exit(1)

    print(f"Reading {html_path}...")
    with open(html_path, "r", encoding="utf-8") as f:
        html_content = f.read()

    original_size = len(html_content.encode("utf-8"))
    print(f"Original HTML size: {original_size} bytes")

    header_content = f'''#pragma once
// ============================================================
// Boat Controller — Web UI Embedded in Flash PROGMEM
// Auto-generated by web-ui/compress.py
// ============================================================

#include <Arduino.h>

static const char WEB_UI_HTML[] PROGMEM = R"rawliteral({html_content})rawliteral";

static const size_t WEB_UI_HTML_LEN = sizeof(WEB_UI_HTML) - 1;
'''

    os.makedirs(os.path.dirname(output_header), exist_ok=True)
    with open(output_header, "w", encoding="utf-8") as f:
        f.write(header_content)

    print(f"Successfully generated {output_header} ({len(header_content.encode('utf-8'))} bytes)")

if __name__ == "__main__":
    main()
