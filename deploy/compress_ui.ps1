<#
.SYNOPSIS
    Compress / Embed web-ui/index.html into shore-station/src/web_ui.h
.DESCRIPTION
    Reads the standalone web HUD HTML source and converts it into
    a C++ PROGMEM header ready to be served by the ESP32 AsyncWebServer.
#>

$ErrorActionPreference = "Stop"

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$rootDir = Split-Path -Parent $scriptDir
$htmlFile = Join-Path $rootDir "web-ui\index.html"
$headerFile = Join-Path $rootDir "shore-station\src\web_ui.h"

Write-Host "========================================" -ForegroundColor Cyan
Write-Host " Rescue Boat UI Header Generator" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan

if (-not (Test-Path $htmlFile)) {
    Write-Error "Source HTML not found at $htmlFile"
    exit 1
}

Write-Host "Reading HTML source from: $htmlFile" -ForegroundColor Yellow
$htmlContent = [System.IO.File]::ReadAllText($htmlFile, [System.Text.Encoding]::UTF8)

$headerTemplate = @"
#pragma once
// ============================================================
// Shore Station — Web UI Embedded in Flash PROGMEM
// Auto-generated by deploy/compress_ui.ps1
// ============================================================

#include <Arduino.h>

static const char WEB_UI_HTML[] PROGMEM = R"rawliteral($htmlContent)rawliteral";

static const size_t WEB_UI_HTML_LEN = sizeof(WEB_UI_HTML) - 1;
"@

Write-Host "Writing embedded header to: $headerFile" -ForegroundColor Yellow
[System.IO.File]::WriteAllText($headerFile, $headerTemplate, [System.Text.Encoding]::UTF8)

$fileSize = (Get-Item $headerFile).Length
Write-Host "[OK] Successfully generated web_ui.h ($fileSize bytes)" -ForegroundColor Green
